  function watch() {
    var h = document.getElementById('sales');
    if (!h || h.__saleObs) return;
    h.__saleObs = true;
    new MutationObserver(function () {
      if (STATE.draw) return;
      if (!hasBoard(h)) { draw(); }
    }).observe(h, { childList: true });
  }

